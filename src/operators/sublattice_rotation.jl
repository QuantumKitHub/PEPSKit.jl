#
## Sublattice rotations
#
# A sublattice rotation with angles `(θr, θc)` and generator `G` is the product unitary
#     U = ∏_x exp(i φ_x G_x),    φ_x = θr (x[1] - 1) + θc (x[2] - 1),
# see https://arxiv.org/abs/2311.05534. Operators are transformed as `U' * O * U`, states as
# `U * ψ`, such that ⟨Uψ|O|Uψ⟩ = ⟨ψ|U'OU|ψ⟩.

# rotation angle at site `x`, measured with respect to site (1, 1)
_rotation_angle(angles, x::CartesianIndex{2}) = angles[1] * (x[1] - 1) + angles[2] * (x[2] - 1)
_rotation_angle(angles, x::NTuple{2, Int}) = _rotation_angle(angles, CartesianIndex(x))

function _iszero_mod2π(φ::Real; atol::Real = 1.0e-10)
    m = mod(φ, 2π)
    return min(m, 2π - m) < atol
end

"""
    rotation_generator(T::Type{<:Number}, P::ElementarySpace, axis::Symbol)

Spin operator ``S^α`` along `axis` (`:x`, `:y` or `:z`) acting on the physical space `P`,
where the spin is inferred from `dim(P) = 2 * spin + 1`. This generates the sublattice
rotation of an [`InfiniteTriangular`](@ref) lattice.
"""
function rotation_generator(T::Type{<:Number}, P::ElementarySpace, axis::Symbol)
    f = if axis === :x
        SO.S_x
    elseif axis === :y
        SO.S_y
    elseif axis === :z
        SO.S_z
    else
        throw(ArgumentError("rotation axis should be `:x`, `:y` or `:z`"))
    end
    spin = (dim(P) - 1) // 2
    G = f(complex(T), sectortype(P); spin)
    space(G, 1) == P || throw(
        SpaceMismatch(
            "cannot construct the spin-$spin rotation generator on physical space $P; \
            pass the generator explicitly to `rotate_sublattices`"
        )
    )
    return G
end
@non_differentiable rotation_generator(args...)

_rotation_unitary(G::AbstractTensorMap, φ::Real) = exp((im * φ) * G)

# restore real scalar types when the rotation keeps the tensor real (e.g. for `axis = :y`)
function _maybe_real(t::AbstractTensorMap, T::Type{<:Number})
    T <: Real || return t
    norm(imag(t)) <= sqrt(eps(real(scalartype(t)))) * max(norm(t), 1) || throw(
        ArgumentError(
            "the sublattice rotation turns a real tensor into a complex one; \
            use complex scalars instead"
        )
    )
    return real(t)
end

# U' * O * U for a dense term
function _rotate_term(O::AbstractTensorMap, G, φs)
    U = mapreduce(φ -> _rotation_unitary(G, φ), ⊗, φs)
    return _maybe_real(U' * O * U, scalartype(O))
end
# rotate a tensor product term factor by factor
function _rotate_term(O::TensorProductTerm, G, φs)
    return map(O, φs) do o, φ
        u = _rotation_unitary(G, φ)
        return _maybe_real(u' * o * u, scalartype(o))
    end
end
_rotate_term(::MPOTerm, G, φs) = throw(
    ArgumentError("sublattice rotations of MPO terms are not supported")
)

_dense_term(O::AbstractTensorMap) = O
_dense_term(O::TensorProductTerm) = reduce(⊗, O)
_dense_term(O::MPOTerm) = throw(
    ArgumentError("sublattice rotations of MPO terms are not supported")
)

# A term is invariant under all global rotations generated by `G` iff it commutes with
# `exp(i φ G)^{⊗N}` for a generic angle φ.
function _is_rotation_invariant(O, G)
    Odense = _dense_term(O)
    N = numin(Odense)
    U = mapreduce(_ -> _rotation_unitary(G, 1.0), ⊗, 1:N)
    return isapprox(U' * Odense * U, Odense; atol = sqrt(eps(real(scalartype(Odense)))) * max(norm(Odense), 1))
end

"""
    rotate_sublattices(O::LocalOperator, angles::Tuple{Real, Real}, G::AbstractTensorMap)
    rotate_sublattices(O::LocalOperator, lattice::InfiniteTriangular)

Transform the operator `O` into the frame of the sublattice rotation
``U = \\prod_x \\exp(i φ_x G_x)``, with ``φ_{[r, c]} = θ_r (r - 1) + θ_c (c - 1)``, i.e.
return ``U^† O U``. The angles `(θr, θc)` and generator are either given explicitly, or
taken from `lattice` (see [`InfiniteTriangular`](@ref)).

Terms that commute with the total generator only depend on the relative angles between the
sites they act on, and can be rotated for any unit cell. Other terms are rotated with the
absolute angles, which requires the rotation to be commensurate with the unit cell of `O`,
i.e. `θr * size(O, 1)` and `θc * size(O, 2)` should be multiples of `2π`. If this is not the
case, consider enlarging the unit cell of `O` with `repeat`.

The expectation value of the returned operator in a PEPS `ψ` equals the expectation value
of `O` in the rotated state ``U |ψ⟩``, which is constructed explicitly by
`rotate_sublattices(ψ, ...)`.
"""
function rotate_sublattices(O::LocalOperator, angles::Tuple{Real, Real}, G::AbstractTensorMap)
    all(iszero, angles) && return O
    numin(G) == numout(G) == 1 || throw(ArgumentError("the rotation generator should be a one-site operator"))
    all(==(space(G, 1)), physicalspace(O)) ||
        throw(SpaceMismatch("the rotation generator does not act on the physical spaces of the operator"))
    commensurate = _iszero_mod2π(angles[1] * size(O, 1)) && _iszero_mod2π(angles[2] * size(O, 2))
    terms = map(collect(O.terms)) do (inds, term)
        φs = if _is_rotation_invariant(term, G)
            φ₀ = _rotation_angle(angles, first(inds))
            [_rotation_angle(angles, ind) - φ₀ for ind in inds]
        elseif commensurate
            [_rotation_angle(angles, ind) for ind in inds]
        else
            throw(
                ArgumentError(
                    "the term acting on $inds is not invariant under the rotation and the angles \
                    $angles are incommensurate with the $(size(O)) unit cell of the operator; \
                    enlarge the unit cell of the operator, e.g. with `repeat`"
                )
            )
        end
        return inds => _rotate_term(term, G, φs)
    end
    return LocalOperator(physicalspace(O), terms...)
end
function rotate_sublattices(O::LocalOperator, lattice::InfiniteTriangular)
    has_sublattice_rotation(lattice) || return O
    P = first(physicalspace(O))
    G = rotation_generator(scalartype(O), P, lattice.axis)
    return rotate_sublattices(O, lattice.rotation, G)
end
rotate_sublattices(O::LocalOperator, lattice) = O

"""
    _rotation_supercell(cell::TriangularUnitCell, angles; maxfactor=24) -> TriangularUnitCell

Smallest (sheared) supercell of `cell` on which the sublattice rotation with `angles` is
periodic, i.e. such that both translations of the supercell rotate by a multiple of `2π`.
"""
function _rotation_supercell(cell::TriangularUnitCell, angles; maxfactor::Int = 24)
    Nr, Nc = size(cell)
    best = nothing
    for a in 1:maxfactor
        _iszero_mod2π(angles[2] * a * Nc) || continue
        for m in 1:maxfactor, n in 0:(a - 1)
            shift = m * cell.shift + n * Nc
            _iszero_mod2π(angles[1] * m * Nr + angles[2] * shift) || continue
            if isnothing(best) || a * m < best[1] * best[2]
                best = (m, a, shift)
            end
        end
    end
    isnothing(best) && throw(
        ArgumentError(
            "the rotation angles $angles are incommensurate with the $(size(cell)) unit cell \
            (shift $(cell.shift)) up to supercells of $maxfactor × $maxfactor unit cells"
        )
    )
    m, a, shift = best
    return TriangularUnitCell((m * Nr, a * Nc), shift)
end
@non_differentiable _rotation_supercell(args...)

"""
    rotate_sublattices(peps::InfinitePEPSTriangular, angles::Tuple{Real, Real}, G::AbstractTensorMap)
    rotate_sublattices(peps::InfinitePEPSTriangular, lattice::InfiniteTriangular)

Explicitly construct the rotated state ``U |ψ⟩`` of the sublattice rotation
``U = \\prod_x \\exp(i φ_x G_x)``, with ``φ_{[r, c]} = θ_r (r - 1) + θ_c (c - 1)``.
The result is stored in the smallest (sheared) supercell of the unit cell of `peps` on which
the rotation is periodic, see [`TriangularUnitCell`](@ref). For instance, a single-site
`peps` with `angles = (-2π/3, 2π/3)` yields the three-sublattice state `[A B C]` with
`shift = 1`, compatible with [`InfiniteTriangularThreeSublattice`](@ref), while
`angles = (π, π)` yields `[A B]` with `shift = 1`, i.e. `[A B; B A]`.

For half-integer spins, the rotation of a site by `2π` gives a sign `-1`, which may lead
to sign differences between equivalent sites that do not affect any expectation values.
"""
function rotate_sublattices(peps::InfinitePEPSTriangular, angles::Tuple{Real, Real}, G::AbstractTensorMap)
    cell = _cell(peps)
    supercell = _rotation_supercell(cell, angles)
    sites = CartesianIndices(size(supercell))
    tensors = map(sites) do I
        A = peps[_site(cell, Tuple(I)...)...]
        φ = _rotation_angle(angles, I)
        return _maybe_real(_rotation_unitary(G, φ) * A, scalartype(A))
    end
    return InfinitePEPSTriangular(tensors; shift = supercell.shift)
end
function rotate_sublattices(peps::InfinitePEPSTriangular, lattice::InfiniteTriangular)
    has_sublattice_rotation(lattice) || return peps
    G = rotation_generator(scalartype(peps), physicalspace(peps[1, 1]), lattice.axis)
    return rotate_sublattices(peps, lattice.rotation, G)
end
