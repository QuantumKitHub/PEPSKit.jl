"""
$(TYPEDEF)

Environment of a boundary MPS contraction of a network with a single-site unit cell which is
invariant under rotations and Hermitian reflections.

Such an environment consists of a single uniform MPS approximating the leading eigenvector
of the row-to-row transfer matrix of the network, given in its left- and right-gauged form
`AL` and `AR` along with the corresponding bond tensor `C`, as well as the left and right
environments `GL` and `GR`. The latter are obtained as the left and right fixed points of
the MPS-network-MPS transfer matrix.

## Fields

$(TYPEDFIELDS)

## Constructors

    C4vBoundaryMPSEnv([f=randn, T=scalartype(network)], network, Venv::ElementarySpace)
    C4vBoundaryMPSEnv(env::CTMRGEnv, network)

Construct a C4v boundary MPS environment for a given `network` with all virtual
environment spaces given by `Venv`, where the tensor entries are generated by `f` with
scalar type `T`. Here, `network` can be an [`InfiniteSquareNetwork`](@ref) or anything that
can be converted into one, such as an [`InfinitePEPS`](@ref) or an
[`InfinitePartitionFunction`](@ref).

Alternatively, the boundary MPS can be initialized from the north edge of a CTMRG
environment `env` of the same network. Starting from a CTMRG environment that was grown
from a product state, for example using [`ProductStateInitialization`](@ref), avoids the
subdominant fixed points that a boundary MPS contraction started from a random MPS can
converge to.
"""
struct C4vBoundaryMPSEnv{TC, TE}
    "left-gauged MPS tensor"
    AL::TE
    "right-gauged MPS tensor"
    AR::TE
    "MPS bond tensor"
    C::TC
    "left environment"
    GL::TE
    "right environment"
    GR::TE
end

"""
$(TYPEDEF)

Environment of a boundary MPS contraction of a network with an arbitrary unit cell and no
assumed spatial symmetries.

Such an environment consists of a top boundary MPS approximating the leading right
eigenvector of the row-to-row transfer matrix of the network, a bottom boundary MPS
approximating its leading left eigenvector, and the environments of both. Every field is a
matrix with the size of the unit cell, and every tensor is indexed by its position in the
network in the same way as the tensors of a [`CTMRGEnv`](@ref):

* `ALt[r, c]` lies between rows `r` and `r + 1` of the network at column `c`, like the north
  edge `edges[NORTH, r, c]`. Similarly, `ALb[r, c]` lies between rows `r - 1` and `r`, like the
  south edge `edges[SOUTH, r, c]`, and has the same leg order as a south edge.
* `Ct[r, c]` and `Cb[r, c]` are the bonds to the right of column `c`, such that
  `ALt[r, c] Ct[r, c] = Ct[r, c - 1] ARt[r, c]` and `ALb[r, c] Cb[r, c - 1] = Cb[r, c] ARb[r, c]`.
* The environments `GL*[r, c]` and `GR*[r, c]` belong to row `r` of the network and lie to the
  right and to the left of column `c`, like the west edge `edges[WEST, r, c]` and the east edge
  `edges[EAST, r, c]`. The environments of the top MPS lie between `ALt[r - 1, :]` and
  `ALt[r, :]`, those of the bottom MPS between `ALb[r + 1, :]` and `ALb[r, :]`, and the mixed
  environments between `ALt[r - 1, :]` and `ALb[r + 1, :]`.

The bottom boundary MPS is computed as the top boundary MPS of the network rotated by 180
degrees.

## Fields

$(TYPEDFIELDS)

## Constructors

    BoundaryMPSEnv([f=randn, T=scalartype(network)], network, Venv::ElementarySpace)
    BoundaryMPSEnv(env::CTMRGEnv, network)

Construct a boundary MPS environment for a given `network` with all virtual environment
spaces given by `Venv`, where the tensor entries are generated by `f` with scalar type `T`.
Here, `network` can be an [`InfiniteSquareNetwork`](@ref) or anything that can be converted
into one, such as an [`InfinitePEPS`](@ref) or an [`InfinitePartitionFunction`](@ref).

Alternatively, the top and bottom boundary MPS can be initialized from the north and south
edges of a CTMRG environment `env` of the same network. Starting from a CTMRG environment
that was grown from a product state, for example using [`ProductStateInitialization`](@ref),
avoids the subdominant fixed points that a boundary MPS contraction started from random MPS
can converge to.
"""
struct BoundaryMPSEnv{TC, TE}
    "left-gauged tensors of the top MPS"
    ALt::Matrix{TE}
    "right-gauged tensors of the top MPS"
    ARt::Matrix{TE}
    "bond tensors of the top MPS"
    Ct::Matrix{TC}
    "left environments of the top MPS"
    GLt::Matrix{TE}
    "right environments of the top MPS"
    GRt::Matrix{TE}
    "left-gauged tensors of the bottom MPS"
    ALb::Matrix{TE}
    "right-gauged tensors of the bottom MPS"
    ARb::Matrix{TE}
    "bond tensors of the bottom MPS"
    Cb::Matrix{TC}
    "left environments of the bottom MPS"
    GLb::Matrix{TE}
    "right environments of the bottom MPS"
    GRb::Matrix{TE}
    "left mixed environments between the top and bottom MPS"
    GLm::Matrix{TE}
    "right mixed environments between the top and bottom MPS"
    GRm::Matrix{TE}
end

const BoundaryMPSEnvs = Union{C4vBoundaryMPSEnv, BoundaryMPSEnv}

# unpack an environment into its constituent tensors or matrices of tensors
_unpack(env::C4vBoundaryMPSEnv) = (env.AL, env.AR, env.C, env.GL, env.GR)
function _unpack(env::BoundaryMPSEnv)
    return (
        env.ALt, env.ARt, env.Ct, env.GLt, env.GRt,
        env.ALb, env.ARb, env.Cb, env.GLb, env.GRb,
        env.GLm, env.GRm,
    )
end

# all tensors of an environment, and a new environment from `f` applied to all of them
_tensors(env::C4vBoundaryMPSEnv) = _unpack(env)
_tensors(env::BoundaryMPSEnv) = Iterators.flatten(_unpack(env))
_map_tensors(f, env::C4vBoundaryMPSEnv) = C4vBoundaryMPSEnv(map(f, _unpack(env))...)
_map_tensors(f, env::BoundaryMPSEnv) = BoundaryMPSEnv(map(x -> map(f, x), _unpack(env))...)
function _map_tensors(f, env₁::C4vBoundaryMPSEnv, env₂::C4vBoundaryMPSEnv)
    return C4vBoundaryMPSEnv(map(f, _unpack(env₁), _unpack(env₂))...)
end
function _map_tensors(f, env₁::BoundaryMPSEnv, env₂::BoundaryMPSEnv)
    return BoundaryMPSEnv(map((x, y) -> map(f, x, y), _unpack(env₁), _unpack(env₂))...)
end

Base.size(env::BoundaryMPSEnv, args...) = size(env.ALt, args...)

#
## initialization
#

# periodic access to a matrix of tensors with the size of the unit cell
_at(X::AbstractMatrix, r::Int, c::Int) = X[mod1(r, size(X, 1)), mod1(c, size(X, 2))]

# the matrix with entries `f(r, c)` over a unit cell of size `(rows, cols)`
_cellmap(f, (rows, cols)::Tuple{Int, Int}) = [f(r, c) for r in 1:rows, c in 1:cols]

"""
    _initialize_GL([f=randn, T=scalartype(A)], A::GenericMPSTensor, O)
    _initialize_GR([f=randn, T=scalartype(A)], A::GenericMPSTensor, O)

Initialize a left or right environment for an MPS tensor `A` and a local network tensor
`O`, with entries generated by `f` and scalar type `T`.
"""
function _initialize_GL(f, ::Type{T}, A::GenericMPSTensor, O) where {T}
    V = left_virtualspace(A) ⊗ _elementwise_dual(west_virtualspace(O)) ← left_virtualspace(A)
    return f(T, V)
end
function _initialize_GR(f, ::Type{T}, A::GenericMPSTensor, O) where {T}
    V = right_virtualspace(A) ⊗ _elementwise_dual(east_virtualspace(O)) ← right_virtualspace(A)
    return f(T, V)
end

# Random environments of a top MPS `At` on `network`, either its own (`mixed = false`, with
# `Ab = At`) or the mixed ones with a bottom MPS `Ab` (`mixed = true`). The bottom leg of a
# left environment is the left virtual space of the conjugated top MPS below it, or the
# right virtual space of the bottom MPS in its own leg order, and similarly on the right.
function _initialize_environments(f, ::Type{T}, At, Ab, network; mixed::Bool) where {T}
    GL = _cellmap(size(At)) do r, c
        A, B, O = _at(At, r - 1, c + 1), _at(Ab, r + Int(mixed), c + 1), network[r, c + 1]
        Vb = mixed ? right_virtualspace(B) : left_virtualspace(B)
        return f(T, Vb ⊗ _elementwise_dual(west_virtualspace(O)) ← left_virtualspace(A))
    end
    GR = _cellmap(size(At)) do r, c
        A, B, O = _at(At, r - 1, c - 1), _at(Ab, r + Int(mixed), c - 1), network[r, c - 1]
        Vb = mixed ? left_virtualspace(B) : right_virtualspace(B)
        return f(T, right_virtualspace(A) ⊗ _elementwise_dual(east_virtualspace(O)) ← Vb)
    end
    return GL, GR
end

for E in (:C4vBoundaryMPSEnv, :BoundaryMPSEnv)
    @eval begin
        function $E(network::InfiniteSquareNetwork, Venv::ElementarySpace)
            return $E(randn, scalartype(network), network, Venv)
        end
        function $E(state::Union{InfinitePEPS, InfinitePartitionFunction}, args...)
            return $E(InfiniteSquareNetwork(state), args...)
        end
        function $E(f, T, state::Union{InfinitePEPS, InfinitePartitionFunction}, args...)
            return $E(f, T, InfiniteSquareNetwork(state), args...)
        end
        function $E(env::CTMRGEnv, state::Union{InfinitePEPS, InfinitePartitionFunction})
            return $E(env, InfiniteSquareNetwork(state))
        end
    end
end

function C4vBoundaryMPSEnv(
        f, ::Type{T}, network::InfiniteSquareNetwork, Venv::ElementarySpace
    ) where {T}
    size(network) == (1, 1) ||
        throw(ArgumentError("C4v boundary MPS environments require a single-site unit cell"))
    O = network[1, 1]

    # initialize the MPS tensors by constructing an actual MPS, this improves stability
    A = f(T, Venv ⊗ _elementwise_dual(north_virtualspace(O)) ← Venv)
    return _c4v_boundary_mps_env(f, T, InfiniteMPS([A]), O)
end
function C4vBoundaryMPSEnv(env::CTMRGEnv, network::InfiniteSquareNetwork)
    size(network) == size(env)[2:3] == (1, 1) ||
        throw(ArgumentError("C4v boundary MPS environments require a single-site unit cell"))
    T = promote_type(scalartype(env), scalartype(network))
    A = _with_scalartype(T, env.edges[NORTH, 1, 1])
    return _c4v_boundary_mps_env(randn, T, InfiniteMPS([A]), network[1, 1])
end
_with_scalartype(::Type{T}, t) where {T} = scalartype(t) == T ? copy(t) : copy!(similar(t, T), t)

function _c4v_boundary_mps_env(f, ::Type{T}, mps::InfiniteMPS, O) where {T}
    AL, AR, C = only(mps.AL), only(mps.AR), only(mps.C)
    GL = _initialize_GL(f, T, AL, O)
    GR = _initialize_GR(f, T, AR, O)
    return C4vBoundaryMPSEnv(AL, AR, C, GL, GR)
end

function BoundaryMPSEnv(
        f, ::Type{T}, network::InfiniteSquareNetwork, Venv::ElementarySpace
    ) where {T}
    # MPS tensors at the positions of the top MPS on top of the network `n`
    random_mps(n) = _cellmap(size(n)) do r, c
        return f(T, Venv ⊗ _elementwise_dual(north_virtualspace(n[r + 1, c])) ← Venv)
    end
    top = _multiline_mps(random_mps(network))
    bottom = _multiline_mps(random_mps(rot180(network)))
    return _boundary_mps_env(f, T, top, bottom, network)
end
function BoundaryMPSEnv(env::CTMRGEnv, network::InfiniteSquareNetwork)
    size(network) == size(env)[2:3] ||
        throw(ArgumentError("the CTMRG environment and the network have different unit cells"))
    T = promote_type(scalartype(env), scalartype(network))
    edges = map(e -> _with_scalartype(T, e), env.edges)
    # the north and south edges lie at the positions of the top and bottom MPS tensors
    top = _multiline_mps(edges[NORTH, :, :])
    bottom = _multiline_mps(_rotate_sites(edges[SOUTH, :, :]))
    return _boundary_mps_env(randn, T, top, bottom, network)
end

# pack a top boundary MPS and a bottom one, both given as a `MultilineMPS` with the bottom
# one in the frame of `rot180(network)`, into an environment with random initial guesses for
# all environments
function _boundary_mps_env(f, ::Type{T}, top, bottom, network) where {T}
    ALt, ARt, Ct = _mps_tensors(top)
    GLt, GRt = _initialize_environments(f, T, ALt, ALt, network; mixed = false)
    ALb′, ARb′, Cb′ = _mps_tensors(bottom)
    GLb′, GRb′ = _initialize_environments(f, T, ALb′, ALb′, rot180(network); mixed = false)
    ALb, ARb, Cb, GLb, GRb = rotate_bottom((ALb′, ARb′, Cb′, GLb′, GRb′))
    GLm, GRm = _initialize_environments(f, T, ALt, ALb, network; mixed = true)
    return BoundaryMPSEnv(ALt, ARt, Ct, GLt, GRt, ALb, ARb, Cb, GLb, GRb, GLm, GRm)
end

#
## conversion between matrices of tensors and MPSKit's multiline objects
#

# Row `r` of a `MultilineMPS` lies directly above row `r` of the network, and the environments
# `GLs[c]` and `GRs[c]` of its row `r` lie to the left and right of site `(r, c)`, which in
# the positions of a `BoundaryMPSEnv` are `ALt[r - 1, c]`, `GLt[r, c - 1]` and `GRt[r, c + 1]`.
function _multiline_mps(A::Matrix)
    return MultilineMPS(_cellmap((r, c) -> _at(A, r - 1, c), size(A)))
end
function _multiline_mps(AL::Matrix, C::Matrix)
    return MultilineMPS(
        _cellmap((r, c) -> _at(AL, r - 1, c), size(AL)),
        [_at(C, r - 1, size(C, 2)) for r in axes(C, 1)],
    )
end
function _mps_tensors(mps::MultilineMPS)
    dims = (size(mps, 1), length(mps[1]))
    return map((:AL, :AR, :C)) do f
        return _cellmap((r, c) -> getproperty(mps[r + 1], f)[c], dims)
    end
end
function _multiline_environments(GL::Matrix, GR::Matrix)
    envs = map(axes(GL, 1)) do r
        GLs = PeriodicVector([_at(GL, r, c - 1) for c in axes(GL, 2)])
        GRs = PeriodicVector([_at(GR, r, c + 1) for c in axes(GR, 2)])
        return InfiniteEnvironments(GLs, GRs)
    end
    return MPSKit.Multiline(PeriodicVector(envs))
end
function _mps_environments(envs)
    dims = (length(envs), length(envs[1].GLs))
    GL = _cellmap((r, c) -> envs[r].GLs[c + 1], dims)
    GR = _cellmap((r, c) -> envs[r].GRs[c - 1], dims)
    return GL, GR
end

#
## rotation of the bottom boundary MPS
#

# Between the original frame and the frame of `rot180(network)`, in which it is a top MPS,
# the site tensors and environments of the bottom MPS rotate like the network,
# `X′[r, c] = X[R - r + 1, N - c + 1]`, and its bonds, which lie to the right of a column in
# both frames, with an additional shift, `C′[r, c] = C[R - r + 1, N - c]`. Both maps are their
# own inverse.
_rotate_sites(X::AbstractMatrix) = _cellmap((r, c) -> _at(X, size(X, 1) - r + 1, size(X, 2) - c + 1), size(X))
_rotate_bonds(X::AbstractMatrix) = _cellmap((r, c) -> _at(X, size(X, 1) - r + 1, size(X, 2) - c), size(X))

"""
    rotate_bottom((AL, AR, C, GL, GR))

Map a bottom boundary MPS and its environments, or any variables or cotangents with the same
structure, between the original frame and the frame of the network rotated by 180 degrees,
in which it is a top boundary MPS. The map is its own inverse.
"""
function rotate_bottom((AL, AR, C, GL, GR))
    return (
        _rotate_sites(AL), _rotate_sites(AR), _rotate_bonds(C),
        _rotate_sites(GL), _rotate_sites(GR),
    )
end

# the top and bottom boundary MPS of an environment with their own environments, the bottom
# one in the frame of `rot180(network)`
_top(env::BoundaryMPSEnv) = (env.ALt, env.ARt, env.Ct, env.GLt, env.GRt)
_bottom(env::BoundaryMPSEnv) = rotate_bottom((env.ALb, env.ARb, env.Cb, env.GLb, env.GRb))

