function Base.:(==)(env₁::E, env₂::E) where {E <: BoundaryMPSEnvs}
    return all(splat(==), zip(_tensors(env₁), _tensors(env₂)))
end
function Base.isapprox(env₁::E, env₂::E; kwargs...) where {E <: BoundaryMPSEnvs}
    return all(zip(_tensors(env₁), _tensors(env₂))) do (t₁, t₂)
        return isapprox(t₁, t₂; kwargs...)
    end
end

Base.real(env::BoundaryMPSEnvs) = _map_tensors(real, env)
Base.complex(env::BoundaryMPSEnvs) = _map_tensors(complex, env)
Base.similar(env::BoundaryMPSEnvs) = _map_tensors(similar, env)
Base.copy(env::BoundaryMPSEnvs) = _map_tensors(copy, env)

Base.:+(env₁::E, env₂::E) where {E <: BoundaryMPSEnvs} = _map_tensors(+, env₁, env₂)
Base.:-(env₁::E, env₂::E) where {E <: BoundaryMPSEnvs} = _map_tensors(-, env₁, env₂)
Base.:*(α::Number, env::BoundaryMPSEnvs) = _map_tensors(Base.Fix1(*, α), env)

"""
    update!(env::C4vBoundaryMPSEnv, env´::C4vBoundaryMPSEnv)
    update!(env::BoundaryMPSEnv, env´::BoundaryMPSEnv)

Update the environment `env` in-place with the contents of `env´`.
"""
function update!(env::E, env´::E) where {E <: C4vBoundaryMPSEnv}
    foreach(splat(copy!), zip(_unpack(env), _unpack(env´)))
    return env
end
function update!(env::E, env´::E) where {E <: BoundaryMPSEnv}
    foreach(splat(copyto!), zip(_unpack(env), _unpack(env´)))
    return env
end

